function icon(name, size = 16, attrs = '') {
  const body = ICONS[name] || ICONS.file;
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" ${attrs}>${body}</svg>`;
}

// Replaces <span data-icon="name"> placeholders in static markup.
function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    const size = Number(el.dataset.size) || (el.classList.contains('brand-mark') ? 17 : 16);
    el.innerHTML = icon(el.dataset.icon, size);
    el.removeAttribute('data-icon');
  }
}

